//! Device-agnostic user intents.
//!
//! Every input source (keyboard now, phone later) translates its raw input into
//! these. Screens only ever see an `Action`, never a key code or a phone message.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Action {
    Up,
    Down,
    Left,
    Right,
    /// Activate the focused item (Enter / phone tap).
    Select,
    /// Step out one level (Esc / phone back).
    Back,
    /// Return to the launcher from anywhere.
    Home,
    /// Context options for the focused item.
    Menu,
}

/// Where an action came from. For logging and diagnostics only: screens must
/// not change behaviour based on the source.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceKind {
    Keyboard,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InputEvent {
    pub action: Action,
    /// True when generated by holding a key down (auto-repeat).
    pub repeat: bool,
    pub source: SourceKind,
}
