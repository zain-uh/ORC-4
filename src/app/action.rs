//! Device-agnostic user intents.
//!
//! Every input source (keyboard now, phone later) translates its raw input into
//! these. Screens only ever see an `Action`, never a key code or a phone message.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Action {
    Up,
    Down,
    Left,
    Right,
    /// Activate the focused item (Enter / phone tap).
    Select,
    /// Step out one level (Esc / phone back).
    Back,
    /// Return to the launcher from anywhere.
    Home,
    /// Context options for the focused item.
    Menu,
}

impl Action {
    /// Parses the names used in config files and (later) the phone protocol.
    pub fn from_name(name: &str) -> Option<Self> {
        Some(match name {
            "up" => Self::Up,
            "down" => Self::Down,
            "left" => Self::Left,
            "right" => Self::Right,
            "select" => Self::Select,
            "back" => Self::Back,
            "home" => Self::Home,
            "menu" => Self::Menu,
            _ => return None,
        })
    }
}

/// Where an action came from. For logging and diagnostics only: screens must
/// not change behaviour based on the source.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceKind {
    Keyboard,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InputEvent {
    pub action: Action,
    /// True when generated by holding a key down (auto-repeat).
    pub repeat: bool,
    pub source: SourceKind,
}

/// Typing, from the phone's keyboard or a physical keyboard. Kept separate
/// from `Action` because it carries text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TextEdit {
    Insert(String),
    Backspace,
    Clear,
    /// "Done" / Enter on the phone keyboard.
    Submit,
}

/// A screen asking for text. Sent to the phone so it can open its keyboard
/// with the current value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TextRequest {
    pub prompt: String,
    pub value: String,
}

/// Things that happened outside the screens that a screen may react to.
#[allow(clippy::enum_variant_names)] // Bluetooth and Wi-Fi notices join in M7/M8
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Notice {
    PhonePaired(String),
    PhoneConnected(String),
    PhoneDisconnected(String),
}
